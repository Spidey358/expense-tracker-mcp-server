"""user_repository.py - example of another file reusing the shared connection."""

import threading

from .database import db

_schema_initialized = False
_schema_lock = threading.Lock()


def create_expenses_table():
    db.execute(
        """
        CREATE TABLE IF NOT EXISTS expenses (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            date DATE NOT NULL,
            amount NUMERIC(10, 2) NOT NULL,
            category VARCHAR(100) NOT NULL,
            subcategory VARCHAR(100) NOT NULL DEFAULT '',
            note VARCHAR(255) NOT NULL DEFAULT ''
        )
        """
    )


def _ensure_schema():
    global _schema_initialized
    if _schema_initialized:
        return
    with _schema_lock:
        if not _schema_initialized:
            create_expenses_table()
            _schema_initialized = True


def add_expense(date: str, amount: float, category: str, subcategory: str = "", note: str = "") -> int:
    _ensure_schema()
    return db.execute(
        """
        INSERT INTO expenses (date, amount, category, subcategory, note)
        VALUES (%s, %s, %s, %s, %s)
        """,
        (date, amount, category, subcategory, note),
    )


def get_expense_by_id(expense_id: int):
    _ensure_schema()
    return db.fetch_one("SELECT * FROM expenses WHERE id = %s", (expense_id,))


def list_expenses(start_date: str = None, end_date: str = None):
    _ensure_schema()
    if start_date and end_date:
        return db.fetch_all(
            "SELECT * FROM expenses WHERE date BETWEEN %s AND %s ORDER BY id",
            (start_date, end_date),
        )
    elif start_date:
        return db.fetch_all(
            "SELECT * FROM expenses WHERE date >= %s ORDER BY id", (start_date,)
        )
    elif end_date:
        return db.fetch_all(
            "SELECT * FROM expenses WHERE date <= %s ORDER BY id", (end_date,)
        )
    else:
        return db.fetch_all("SELECT * FROM expenses ORDER BY id")


def update_expense(
    expense_id: int,
    date: str = None,
    amount: float = None,
    category: str = None,
    subcategory: str = None,
    note: str = None,
) -> int:
    _ensure_schema()
    # Build the UPDATE query dynamically based on provided parameters
    updates = []
    params = []

    if date is not None:
        updates.append("date = %s")
        params.append(date)

    if amount is not None:
        updates.append("amount = %s")
        params.append(amount)

    if category is not None:
        updates.append("category = %s")
        params.append(category)

    if subcategory is not None:
        updates.append("subcategory = %s")
        params.append(subcategory)

    if note is not None:
        updates.append("note = %s")
        params.append(note)

    if not updates:
        raise ValueError("At least one parameter must be provided for update")

    params.append(expense_id)

    query = f"UPDATE expenses SET {', '.join(updates)} WHERE id = %s"
    return db.execute(query, tuple(params))

def summarize_expenses(
    start_date: str = None, end_date: str = None, category: str = None
):
    _ensure_schema()
    query = "SELECT category, subcategory, SUM(amount) as total_amount FROM expenses"
    conditions = []
    params = []

    if start_date:
        conditions.append("date >= %s")
        params.append(start_date)

    if end_date:
        conditions.append("date <= %s")
        params.append(end_date)

    if category:
        conditions.append("category = %s")
        params.append(category)

    if conditions:
        query += " WHERE " + " AND ".join(conditions)

    query += " GROUP BY category, subcategory ORDER BY category, subcategory"

    return db.fetch_all(query, tuple(params))